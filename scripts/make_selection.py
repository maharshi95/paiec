"""Benchmark selection from benchmark_report.csv -> configs/sel/*.yaml (reproducible lists).

Pool (train candidates): tier A/B, public, binarisable, base rate in [0.03, 0.97], per-subject accuracy
  sd >= 0.03 (there is subject signal).
Panel (internal eval, test-like): pool tier A with 8-150 eligible pairs, <= 600k responses, subject sd
  >= 0.05, item sd >= 0.15; stratified by primary domain (<= 3 each, binary-graded preferred, then
  more eligible pairs). Split into 5 folds round-robin within domain-sorted order, so each fold
  mixes domains.
Variants (same panel folds, different training sets):
  sel_pool   train on the whole capped pool minus the held-out fold
  sel_panel  train on the other panel folds only
  sel_ref6   train on the six original reference benchmarks only

    python scripts/make_selection.py --report /fs/clip-scratch/mgor/measurement-db/benchmark_report.csv
"""
import argparse
from pathlib import Path

import pandas as pd
import yaml

REF6 = ["matharena", "mmdocrag", "multi_swebench", "real_webagents", "researchcodebench", "swe_rebench"]


MODELS = {   # model variants written for both dev and hold-out
    "constant": {"predictor": {"name": "constant"}, "acquisition": {"name": "official_random"}},
    "empirical_mean": {"predictor": {"name": "empirical_mean"}, "acquisition": {"name": "official_random"}},
    "beta_shrink": {"predictor": {"name": "beta_shrink"}, "acquisition": {"name": "accept_all"}},
    "irt": {},   # base default (per-benchmark subject terms)
    "irt_share": {"predictor": {"name": "irt", "item_target": "absolute", "beta_var_mult": 4.0, "subject_sharing": True}},
    "mirt_k8_pair": {"predictor": {"name": "mirt", "item_target": "absolute", "beta_var_mult": 4.0, "ndim": 8}},
    **{f"mirt_k{k}": {"predictor": {"name": "mirt", "item_target": "absolute", "beta_var_mult": 4.0, "ndim": k,
                                    "subject_sharing": True}}
       for k in (2, 4, 8, 16)},
}


def write_dev_holdout(panel, universe, base, n_folds, out, n_holdout):
    """Locked hold-out: one benchmark from each of the n_holdout largest primary domains of the panel
    (seeded choice; the six reference benchmarks stay in dev). Dev: the rest in grouped folds.
    Hold-out benchmarks are removed from the dev universe entirely, so they never enter training
    during development; the hold-out configs train on universe - hold-out and test on the hold-out.
    """
    import hashlib
    elig = panel[~panel.benchmark.isin(REF6)].copy()
    elig["h"] = elig.benchmark.map(lambda b: hashlib.md5(b.encode()).hexdigest())
    top = panel.dom1.value_counts().sort_values(ascending=False, kind="stable").index
    holdout = []
    for dom in top:
        c = elig[elig.dom1 == dom].sort_values("h")
        if len(c):
            holdout.append(c.benchmark.iloc[0])
        if len(holdout) == n_holdout:
            break
    dev = panel[~panel.benchmark.isin(holdout)].sort_values(["dom1", "benchmark"]).benchmark.tolist()
    folds = [dev[i::n_folds] for i in range(n_folds)]
    out.mkdir(parents=True, exist_ok=True)
    dev_base = {**base, "data": {**base["data"], "benchmarks": [b for b in universe if b not in holdout]},
                "cv": {**base["cv"], "test_benchmarks": folds}}
    ho_base = {**base, "cv": {**base["cv"], "test_benchmarks": [holdout]}}
    hdr = "# generated by scripts/make_selection.py (do not edit; regenerate)\n"
    (out / "dev_base.yaml").write_text(hdr + yaml.safe_dump(dev_base, sort_keys=False))
    (out / "holdout_base.yaml").write_text(hdr + "# LOCKED: evaluate only milestone configs; never tune on it\n"
                                           + yaml.safe_dump(ho_base, sort_keys=False))
    for split in ("dev", "holdout"):
        for name, over in MODELS.items():
            cfg = {"name": f"{split}_{name}", "base": str(out / f"{split}_base.yaml"), **over}
            (out / f"{split}_{name}.yaml").write_text(yaml.safe_dump(cfg, sort_keys=False))
    (out / "holdout.txt").write_text("\n".join(holdout) + "\n")
    print(f"hold-out {len(holdout)}: {holdout}\ndev {len(dev)} in folds {[len(f) for f in folds]}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", default="/fs/clip-scratch/mgor/measurement-db/benchmark_report.csv")
    ap.add_argument("--out", default="configs/sel")
    ap.add_argument("--folds", type=int, default=5)
    ap.add_argument("--holdout", type=int, default=12, help="locked hold-out benchmarks (1 per top domain)")
    a = ap.parse_args()
    df = pd.read_csv(a.report)
    pool = df[df.tier.isin(["A", "B"]) & df.base_rate.between(0.03, 0.97) & (df.label_sd >= 0.03)].copy()
    cand = pool[(pool.tier == "A") & pool.eval_pairs.between(8, 150) & (pool.n_responses <= 600_000)
                & (pool.label_sd >= 0.05) & (pool.item_sd >= 0.15)].copy()
    cand["dom1"] = cand.domain.fillna("other").str.split(",").str[0]
    cand["pref"] = (cand.rule == "binary").astype(int)
    panel = cand.sort_values(["pref", "eval_pairs"], ascending=False).groupby("dom1").head(3)
    panel = panel.sort_values(["dom1", "benchmark"]).reset_index(drop=True)
    folds = [panel.benchmark[i::a.folds].tolist() for i in range(a.folds)]
    universe = sorted(set(pool.benchmark) | set(REF6))
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    base = {
        "data": {"root": str(Path(a.report).parent), "benchmarks": universe,
                 "binarize": {"mode": "threshold", "threshold": 0.5},
                 "max_responses": 100_000, "max_item_chars": 8000},
        "cv": {"test_benchmarks": folds, "seeds": [0], "max_subjects_per_benchmark": 20,
               "max_eval_items_per_pair": 100},
        "sim": {"evidence_scope": "global"},
        "predictor": {"name": "irt", "item_target": "absolute", "beta_var_mult": 4.0},
        "acquisition": {"name": "uncertainty", "radius": 0.15},
    }
    (out / "base.yaml").write_text("# generated by scripts/make_selection.py\n" + yaml.safe_dump(base, sort_keys=False))
    variants = {"sel_pool": None, "sel_panel": panel.benchmark.tolist(), "sel_ref6": REF6}
    for name, train in variants.items():
        cfg = {"name": name, "base": str(out / "base.yaml")}
        if train:
            cfg["cv"] = {"train_benchmarks": train}
        (out / f"{name}.yaml").write_text(yaml.safe_dump(cfg, sort_keys=False))
    write_dev_holdout(panel, universe, base, a.folds, Path("configs/split"), a.holdout)
    panel.to_csv(out / "panel.csv", index=False)
    pool[["benchmark", "tier", "rule", "n_subjects", "eval_pairs", "n_responses", "base_rate", "domain"]].to_csv(
        out / "pool.csv", index=False)
    print(f"pool {len(pool)} benchmarks; panel {len(panel)} in {a.folds} folds of sizes {[len(f) for f in folds]}")


if __name__ == "__main__":
    main()
